#!/bin/bash

echo "Запуск программы 'Говорящая корова'"
echo "===================================="

# ОШИБКА 1: Неправильная команда (опечатка в command)
if comman -v fortune > /dev/null; then
    MSG=$(fortune 2>/dev/null)
else
    MSG="Привет! Я говорящая корова!"
fi

# Если fortune вернула пустую строку
if [ -z "$MSG" ]; then
    MSG="Мычание коровы..."
fi

# ОШИБКА 2: Незакрытая кавычка (не хватает " в конце)
echo "Корова говорит: $MSG

# ОШИБКА 3: Опечатка в названии программы cowsay
echo "$MSG" | cowsya

# ОШИБКА 4: Неправильная переменная (MESSAGE не существует)
echo "Корова сказала $MESSAGE символов"

# ОШИБКА 5: Проверка $? стоит после echo, а не после cowsay
if [ $? -eq 0 ]; then
    echo "Успех! Корова довольна"
else
    echo "Ошибка: Корова молчит"
fi

echo "===================================="